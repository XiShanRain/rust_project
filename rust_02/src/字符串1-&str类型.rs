fn main(){
    // 'greeting'的类型是是 &str
    //字符串字面量 "Hello, world!" 的类型是 &str,他能被修改，它是一个字符串切片，指向程序二进制中的一个固定位置。
    let greeting = "Hello, world!";
    println!("{}", greeting);
    //字符串字面量是不可变的，这意味着它们在编译的时候就被固定下来。
    //代码中的字符串字面量'Hello, world!'是不可变的，不能使用可变引用来增加或减少它的长度，因为它被分配到一个只读内存区域中，这个区域被程序二进制文件包含。
}